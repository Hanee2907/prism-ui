// Turns the JSON design tokens in tokens/ into every format Prism ships:
//   css        src/lib/generated/{light,dark}.css   (used by the library, committed, checked by CI)
//   platforms  dist/tokens/: JS + TypeScript types, flat JSON, iOS Swift and Android colours
// Usage: node scripts/build-tokens.mjs [css|platforms|all]

import StyleDictionary from 'style-dictionary';

const what = process.argv[2] ?? 'all';
const BASE = ['tokens/base.json', 'tokens/light.json'];
const DARK = [...BASE, 'tokens/dark.json'];
const fromDark = (token) => token.filePath.replace(/\\/g, '/').endsWith('tokens/dark.json');
const isColor = (token) => token.type === 'color';

// CSS names: drop the group for colours, fonts and motion, so color.bg becomes --pr-bg and font.sans becomes --pr-sans.
const DROP = new Set(['color', 'font', 'motion', 'duration']);
StyleDictionary.registerTransform({
  name: 'name/prism',
  type: 'name',
  transform: (token, config) => {
    const path = DROP.has(token.path[0]) ? token.path.slice(1) : token.path;
    return [config.prefix, ...path].join('-').toLowerCase();
  },
});

const HEADER = '/* Generated by scripts/build-tokens.mjs from tokens/*.json. Do not edit by hand. */\n';
const line = (t, pad) => `${pad}--${t.name}: ${t.value};${t.comment ? ` /* ${t.comment} */` : ''}`;

StyleDictionary.registerFormat({
  name: 'css/prism-light',
  format: ({ dictionary }) =>
    `${HEADER}\n:root,\n[data-pr-theme='light'] {\n${dictionary.allTokens.map((t) => line(t, '  ')).join('\n')}\n  color-scheme: light;\n}\n`,
});

StyleDictionary.registerFormat({
  name: 'css/prism-dark',
  format: ({ dictionary }) => {
    const body = (pad) => dictionary.allTokens.map((t) => line(t, pad)).join('\n');
    return (
      `${HEADER}\n[data-pr-theme='dark'] {\n${body('  ')}\n  color-scheme: dark;\n}\n\n` +
      `@media (prefers-color-scheme: dark) {\n  :root:not([data-pr-theme='light']) {\n${body('    ')}\n    color-scheme: dark;\n  }\n}\n`
    );
  },
});

const css = { transforms: ['attribute/cti', 'name/prism'], prefix: 'pr', buildPath: 'src/lib/generated/' };
const out = 'dist/tokens/';
const quiet = { log: { verbosity: 'silent', warnings: 'disabled' } };

async function buildCss() {
  await new StyleDictionary({
    source: BASE,
    ...quiet,
    platforms: { css: { ...css, files: [{ destination: 'light.css', format: 'css/prism-light' }] } },
  }).buildAllPlatforms();
  await new StyleDictionary({
    source: DARK,
    ...quiet,
    platforms: { css: { ...css, files: [{ destination: 'dark.css', format: 'css/prism-dark', filter: fromDark }] } },
  }).buildAllPlatforms();
}

async function buildPlatforms() {
  for (const [mode, source, filter] of [
    ['light', BASE, undefined],
    ['dark', DARK, fromDark],
  ]) {
    const Mode = mode === 'light' ? 'Day' : 'Midnight';
    await new StyleDictionary({
      source,
      ...quiet,
      platforms: {
        js: {
          transformGroup: 'js',
          buildPath: `${out}js/`,
          files: [
            { destination: `${mode}.js`, format: 'javascript/es6', filter },
            { destination: `${mode}.d.ts`, format: 'typescript/es6-declarations', filter },
          ],
        },
        json: {
          transforms: ['attribute/cti', 'name/prism'],
          prefix: 'pr',
          buildPath: `${out}json/`,
          files: [{ destination: `${mode}.json`, format: 'json/flat', filter }],
        },
        ios: {
          transformGroup: 'ios-swift',
          buildPath: `${out}ios/`,
          files: [
            {
              destination: `Prism${Mode}Colors.swift`,
              format: 'ios-swift/class.swift',
              options: { className: `Prism${Mode}Colors` },
              filter: (t) => isColor(t) && (!filter || filter(t)),
            },
          ],
        },
        android: {
          transformGroup: 'android',
          buildPath: `${out}android/values${mode === 'dark' ? '-night' : ''}/`,
          files: [{ destination: 'prism_colors.xml', format: 'android/colors', filter: (t) => isColor(t) && (!filter || filter(t)) }],
        },
      },
    }).buildAllPlatforms();
  }
}

if (what === 'css' || what === 'all') await buildCss();
if (what === 'platforms' || what === 'all') await buildPlatforms();
console.log(`tokens: built ${what}`);
